	$aColumns = array( 'tipo_afiliado_codigo', 'tipo_afiliado_nombre', 'tipo_afiliado_nombre', 'tipo_afiliado_nombre');
	
	/* Indexed column (used for fast and accurate table cardinality) */
	$sIndexColumn = "tipo_afiliado_codigo";
	
